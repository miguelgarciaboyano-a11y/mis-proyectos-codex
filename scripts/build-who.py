"""Reproduce el módulo local desde tablas OMS vendorizadas, sin red.
Datos originales: World Health Organization, GPL >=3; ver vendor/who/LICENSE.md.
Conversión de formato añadida el 2026-10-16. No modifica valores LMS.
"""
import csv, hashlib, json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
manifest=json.loads((root/'vendor/who/manifest.json').read_text())
result={}
for era,names in {'2006':{'weight':'weianthro','height':'lenanthro','bmi':'bmianthro'},'2007':{'weight':'wfawho2007','height':'hfawho2007','bmi':'bfawho2007'}}.items():
    result[era]={}
    for key,name in names.items():
        path=root/'vendor/who'/era/(name+'.txt')
        assert hashlib.sha256(path.read_bytes()).hexdigest()==manifest['files'][str(path.relative_to(root/'vendor/who'))]
        rows=list(csv.DictReader(path.open(newline=''),delimiter='\t'))
        result[era][key]={str(sex):[[int(r['age']),float(r['l']),float(r['m']),float(r['s'])] for r in rows if int(r['sex'])==sex] for sex in [1,2]}
(root/'src/who-data.js').write_text('// Generated by scripts/build-who.py. WHO data, GPL >=3. See vendor/who/LICENSE.md and manifest.json.\nexport const WHO_DATA='+json.dumps(result,separators=(',',':'))+';\n')
